#!/usr/bin/env python3
"""zedcfg - build, install and audit the zed-initiative Zed configuration.

Standard library only (Python 3.9+), one file, no network access.

  build      core/ + enabled packs/ + local.jsonc  ->  dist/
  install    build, then copy dist/ into Zed's config dir(s):
               Linux/macOS  ~/.config/zed
               WSL          ~/.config/zed  AND  the Windows side (%APPDATA%\\Zed)
               Windows      %APPDATA%\\Zed
  doctor     check the tools the enabled packs need, print install commands
             (it never installs anything itself)
  audit      security summary: AI settings, worktree trust, extensions,
             extension capability grants, binaries and task commands
  list       show available packs and whether they are enabled
  new-pack   scaffold packs/<name> from packs/_template
"""
